#!/usr/bin/env python3
"""Derive the storage-only erase adapter; leave the pinned source export byte-identical."""
import hashlib
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[1]
SOURCE = ROOT / "module/zig/src/server/notes/erase_storage.zig"
TARGET = ROOT / "module/zig/src/standalone_erase.zig"


def main():
    original = SOURCE.read_text()
    def rewrite(match):
        path = match[1]
        if path == "std":
            return match[0]
        if path == "../notes_erase_places.zig":
            path = "standalone/erase_places.zig"
        elif path.startswith("../"):
            path = "server/" + path[3:]
        else:
            path = "server/notes/" + path
        return '@import("' + path + '")'
    derived = ("//! GENERATED by tools/derive_standalone_erase.py; storage semantics unchanged.\n"
               + re.sub(r'@import\("([^"\n]+)"\)', rewrite, original))
    TARGET.write_text(derived)
    receipt = {"source": str(SOURCE.relative_to(ROOT)),
               "source_sha256": hashlib.sha256(original.encode()).hexdigest(),
               "derived": str(TARGET.relative_to(ROOT)),
               "derived_sha256": hashlib.sha256(derived.encode()).hexdigest(),
               "changes": "imports only; external engine discovery delegated to explicit no-engine adapter"}
    (ROOT / "module/zig/DERIVED.json").write_text(json.dumps(receipt, indent=2) + "\n")


if __name__ == "__main__":
    main()
